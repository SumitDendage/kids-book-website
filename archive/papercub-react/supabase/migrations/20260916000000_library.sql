-- ---------- customers ----------
create table if not exists public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  email        text,
  name         text,
  kid_age      text,
  drm_password text,                    -- logon for VeryPDF's secure reader, generated by drm-protect
  created_at   timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, name, kid_age)
  values (new.id, new.email, new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'kid_age')
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- entitlements (brief §2, §6, §7) ----------
create table if not exists public.entitlements (
  id           text primary key,                                   -- LW-105842
  user_id      uuid not null references auth.users (id) on delete cascade,
  product_id   text not null references public.products (id),
  licence      text not null references public.licences (id),
  copies       int  not null,
  remaining    int  not null check (remaining >= 0),
  purchased_at timestamptz not null default now(),
  drm_url      text,                                               -- protected file from VeryPDF DRM Protector
  drm_status   text not null default 'pending' check (drm_status in ('pending', 'ready', 'failed', 'none'))
);
create index if not exists entitlements_user_idx on public.entitlements (user_id, purchased_at desc);

create table if not exists public.prints (
  id             bigint generated always as identity primary key,
  entitlement_id text not null references public.entitlements (id) on delete cascade,
  user_id        uuid not null,
  printed_at     timestamptz not null default now()
);

-- ---------- row-level security ----------
alter table public.licences     enable row level security;
alter table public.products     enable row level security;
alter table public.profiles     enable row level security;
alter table public.entitlements enable row level security;
alter table public.prints       enable row level security;

drop policy if exists "licences are public" on public.licences;
create policy "licences are public" on public.licences for select using (true);
drop policy if exists "products are public" on public.products;
create policy "products are public" on public.products for select using (true);
drop policy if exists "own profile" on public.profiles;
create policy "own profile" on public.profiles for select using (auth.uid() = id);
drop policy if exists "own entitlements" on public.entitlements;
create policy "own entitlements" on public.entitlements for select using (auth.uid() = user_id);
drop policy if exists "own prints" on public.prints;
create policy "own prints" on public.prints for select using (auth.uid() = user_id);
-- No insert/update/delete policies: only the functions below (and the service role) write.

