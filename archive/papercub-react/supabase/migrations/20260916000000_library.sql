-- ---------- catalogue (brief §5: allowances are configuration, not code) ----------
create table if not exists public.licences (
  id     text primary key,
  label  text not null,
  copies int  not null check (copies > 0),
  factor int  not null default 1,       -- price multiplier
  sort   int  not null default 0
);
