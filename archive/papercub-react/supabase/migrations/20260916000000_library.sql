-- ---------- functions ----------
create or replace function public.new_licence_id(prefix text default 'LW')
returns text language plpgsql as $$
declare candidate text;
begin
  loop
    candidate := prefix || '-' || (floor(random() * 900000) + 100000)::int::text;
    exit when not exists (select 1 from public.entitlements where id = candidate);
  end loop;
  return candidate;
end $$;

-- checkout(lines): lines = [{"product_id":"sh-alpha","licence":"family","qty":1}, ...]
-- Returns the new entitlements. PAYMENT: this demo takes none — before going
-- live, verify the gateway's payment id for paid lines where marked.
create or replace function public.checkout(lines jsonb)
returns setof public.entitlements language plpgsql security definer set search_path = public as $$
declare
  line   jsonb;
  p      public.products;
  l      public.licences;
  n      int;
  i      int;
  new_id text;
begin
  if auth.uid() is null then raise exception 'sign in first'; end if;
  for line in select * from jsonb_array_elements(lines) loop
    select * into p from public.products where id = line ->> 'product_id';
    if not found then raise exception 'unknown product %', line ->> 'product_id'; end if;
    select * into l from public.licences where id = coalesce(line ->> 'licence', 'individual');
    if not found then raise exception 'unknown licence %', line ->> 'licence'; end if;
    n := greatest(1, least(20, coalesce((line ->> 'qty')::int, 1)));
    if p.price = 0 then n := 1; end if;                     -- a free title is claimed once per checkout
    -- TODO payment: if p.price > 0 then verify the payment id passed alongside the lines
    for i in 1..n loop
      new_id := public.new_licence_id();
      insert into public.entitlements (id, user_id, product_id, licence, copies, remaining, drm_status)
      values (new_id, auth.uid(), p.id, l.id, l.copies, l.copies, case when p.master_path is null then 'none' else 'pending' end);
      return query select * from public.entitlements where id = new_id;
    end loop;
  end loop;
end $$;

-- consume_print(id): one confirmed print session uses one copy. A locked or
-- foreign title is rejected here, whatever the client sends (brief §9).
create or replace function public.consume_print(p_id text)
returns public.entitlements language plpgsql security definer set search_path = public as $$
declare e public.entitlements;
begin
  select * into e from public.entitlements where id = p_id and user_id = auth.uid() for update;
  if not found then raise exception 'not your title'; end if;
  if e.remaining <= 0 then raise exception 'licence used'; end if;
  update public.entitlements set remaining = remaining - 1 where id = p_id returning * into e;
  insert into public.prints (entitlement_id, user_id) values (p_id, auth.uid());
  return e;
end $$;

revoke all on function public.checkout(jsonb) from public, anon;
revoke all on function public.consume_print(text) from public, anon;
grant execute on function public.checkout(jsonb) to authenticated;
grant execute on function public.consume_print(text) to authenticated;
