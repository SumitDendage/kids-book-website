-- 001 — ACCOUNTS. Customers, email confirmation, password reset, sign-in sessions and the
-- security trail live in PostgreSQL. The shop (catalogue, orders, payments, entitlements)
-- stays in the SQLite store and refers to a customer by users.id.
--
-- Secrets are never stored as given: passwords are Argon2id hashes, and every token
-- (session, email confirmation, password reset) is stored as the SHA-256 of a random
-- 256-bit value, so a copy of this database cannot be used to sign in.

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END $$;

CREATE TABLE users (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                   TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  -- always stored lower-case, so the unique index below is case-insensitive
  email                  TEXT NOT NULL CHECK (email = lower(email) AND length(email) BETWEEN 3 AND 254 AND email LIKE '%_@_%'),
  -- Argon2id ($argon2id$…); accounts carried over from the SQLite store keep their scrypt hash
  -- (salt:hash) until the next sign-in, which re-hashes it with Argon2id
  password_hash          TEXT NOT NULL,
  email_verified         BOOLEAN NOT NULL DEFAULT false,
  email_verified_at      TIMESTAMPTZ,
  account_status         TEXT NOT NULL DEFAULT 'pending_verification'
                         CHECK (account_status IN ('pending_verification', 'active', 'suspended')),
  role                   TEXT CHECK (role IN ('parent', 'teacher', 'tutor', 'school')),
  failed_login_attempts  INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
  locked_until           TIMESTAMPTZ,
  password_changed_at    TIMESTAMPTZ,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_login_at          TIMESTAMPTZ,
  CONSTRAINT users_email_key UNIQUE (email),
  CONSTRAINT users_verified_at CHECK (NOT email_verified OR email_verified_at IS NOT NULL),
  CONSTRAINT users_active_is_verified CHECK (account_status <> 'active' OR email_verified)
);
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- the "Accept & Continue" link in the welcome email
CREATE TABLE email_verification_tokens (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash   TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  expires_at   TIMESTAMPTZ NOT NULL,
  used_at      TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_ip   TEXT
);
CREATE INDEX email_verification_tokens_user ON email_verification_tokens (user_id);

-- single-use links from "Forgot password?"
CREATE TABLE password_reset_tokens (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash   TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  expires_at   TIMESTAMPTZ NOT NULL,
  used_at      TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_ip   TEXT
);
CREATE INDEX password_reset_tokens_user ON password_reset_tokens (user_id);

-- one row per signed-in browser; the httpOnly cookie holds the token, this table its hash.
-- /api/auth/refresh-token rotates the token; the previous one keeps working for a few
-- seconds so two tabs refreshing at once do not sign each other out.
CREATE TABLE user_sessions (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash           TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  previous_token_hash  TEXT,
  rotated_at           TIMESTAMPTZ,
  remember             BOOLEAN NOT NULL DEFAULT false,
  ip                   TEXT,
  user_agent           TEXT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_used_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at           TIMESTAMPTZ NOT NULL,
  revoked_at           TIMESTAMPTZ,
  revoke_reason        TEXT
);
CREATE INDEX user_sessions_user ON user_sessions (user_id);
CREATE INDEX user_sessions_previous ON user_sessions (previous_token_hash) WHERE previous_token_hash IS NOT NULL;

-- every sign-in attempt, good or bad
CREATE TABLE login_activity (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT REFERENCES users (id) ON DELETE SET NULL,
  email           TEXT NOT NULL,
  success         BOOLEAN NOT NULL,
  failure_reason  TEXT CHECK (failure_reason IN ('bad_credentials', 'email_unverified', 'account_locked', 'account_suspended', 'rate_limited')),
  ip              TEXT,
  user_agent      TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT login_activity_reason CHECK (success = (failure_reason IS NULL))
);
CREATE INDEX login_activity_user ON login_activity (user_id, created_at DESC);
CREATE INDEX login_activity_at ON login_activity (created_at DESC);

-- the account's security trail: sign-up, confirmation, lockouts, resets, sign-outs
CREATE TABLE security_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
  event_type  TEXT NOT NULL,
  detail      JSONB,
  ip          TEXT,
  user_agent  TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX security_events_user ON security_events (user_id, created_at DESC);
CREATE INDEX security_events_at ON security_events (created_at DESC);
